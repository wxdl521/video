#!/usr/bin/env python3
"""lrc2js.py [assets/song.lrc] [src/lyrics.js] — turn the song's LRC into the karaoke table LY for src/karaoke.js.

The lyrics stay local (src/lyrics.js and assets/*.lrc are gitignored). The first LRC entry is the song's title, not a
sung line, so it is skipped. Each line runs until 0.05 s before the next starts; the last one until --end (default 55.6).
"""
import re, sys
src = sys.argv[1] if len(sys.argv) > 1 else 'assets/song.lrc'
dst = sys.argv[2] if len(sys.argv) > 2 else 'src/lyrics.js'
end = float(next((a.split('=')[1] for a in sys.argv if a.startswith('--end=')), 55.6))
L = []
for line in open(src, encoding='utf-8'):
    m = re.match(r'\[(\d+):(\d+(?:\.\d+)?)\](.*)', line.strip())
    if m: L.append((int(m[1]) * 60 + float(m[2]), m[3].strip()))
L = L[1:]
rows = [f"  [{t:.2f}, {(L[i + 1][0] if i + 1 < len(L) else end) - .05:.2f}, {s!r}]," for i, (t, s) in enumerate(L)]
open(dst, 'w', encoding='utf-8').write('// generated by scripts/lrc2js.py from the song\'s LRC (not committed)\nconst LY = [\n' + '\n'.join(rows) + '\n];\n')
print(f'{dst}: {len(rows)} lines')
